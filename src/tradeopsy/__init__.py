"""tradeopsy —— A股交割单体检报告。

设计原则（写在这里是因为它们决定了后面所有代码的形状）：

1. 金额一律用 Decimal，不用 float。
   金融数据精确到「分」，float 的 0.1 + 0.2 != 0.3 会让你的盈亏对不上券商 App。

2. 费用以交割单为准，不重算。
   真实交割单里的佣金/印花税/过户费是券商算好的结果，
   自己按费率重算，只要费率改过一次就会永久性偏差。
   所以引擎只「读取」费用，不「计算」费用。

3. 先标准化，再记账。
   交割单是流水账（包含红股入账、股息入账、配股缴款等非买卖条目），
   直接拿去做 FIFO 配对必然崩。所以分两层：
   原始记录 -> Event（事件）-> PositionLedger（账本）。

4. 核心零依赖。
   不装 pandas、不装 akshare 也能算完所有交易口径指标。
   需要行情（做 PGR/PLR）时才走可选依赖。
"""

